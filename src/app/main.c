#define DEF_MAIN

#include <stdio.h>
#include "board.h"
#include "drv_pwm.h"
#include "drv_adc.h"
#include "app_supercap.h"
#include "app_rtt.h"

int main(void)
{
    board_init();
    board_init_led_pins();
    (void)Drv_Pwm_Init(DRV_PWM_FREQ_HZ, DRV_PWM_SYNT_FREQ_HZ);
    (void)Drv_Adc_Init();
    app_supercap_init();
    App_RTT_Init();

    printf("SuperCapacitance / HPM5151 (hpm5100evk) start\r\n");
    printf("pwm: %lu Hz, dead time: %lu ns\r\n",
           (unsigned long)Drv_Pwm_GetFreq(), (unsigned long)Drv_Pwm_GetDeadTimeNs());
    printf("adc: %lu Hz conv clock, %lu cycles per conversion\r\n",
           (unsigned long)Drv_Adc_GetConvClock(), (unsigned long)Drv_Adc_GetConvCycles());

    /*
     * PWM 上电保持 0 % 占空比（上管关断）。需要输出时按下面的方式设定：
     *     (void)Drv_Pwm_SetDuty(DRV_PWM_PAIR_0, 500U);   // P0/P1, 50.0 %
     *     (void)Drv_Pwm_SetDuty(DRV_PWM_PAIR_1, 500U);   // P2/P3, 50.0 %
     * Drv_Pwm_Stop() 会先关输出再停计数器，可作为安全停机入口。
     */

    while (1) {
        app_supercap_task();
        /* 后续可在这里加入通信、按键、显示等其它 app 任务 */
    }
    return 0;
}

